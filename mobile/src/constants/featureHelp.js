export const getFeatureHelp = (featureKey) => FEATURE_HELP[featureKey] || null;

export const getLocalizedFeatureHelp = (featureKey, language) => {
  const feature = getFeatureHelp(featureKey);
  if (!feature) {
    return null;
  }

  const languageCode = String(language || 'en').toLowerCase();
  const normalizedLanguage = ['en', 'hi', 'mr'].find((code) => languageCode.startsWith(code)) || 'en';
  const localizedImage = feature.image && typeof feature.image === 'object' && !feature.image.uri
    ? feature.image[normalizedLanguage] || feature.image.en
    : feature.image;

  return {
    ...feature,
    image: localizedImage,
    localized: feature.copy[normalizedLanguage] || feature.copy.en,
  };
};
